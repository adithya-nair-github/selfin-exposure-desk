function tierRank(status: Account["listedStatus"]): number {
  if (status === "listed-snapshot") return 0;
  if (status === "listed-series") return 1;
  return 2;
}

export const ACCOUNTS: Account[] = [...RAW_ACCOUNTS].sort((a, b) => {
  const ta = tierRank(a.listedStatus);
  const tb = tierRank(b.listedStatus);
  if (ta !== tb) return ta - tb;
  const oiA = a.openInterest ?? -1;
  const oiB = b.openInterest ?? -1;
  if (oiA !== oiB) return oiB - oiA;
  const anchorA = a.exposureAnchor ? 1 : 0;
  const anchorB = b.exposureAnchor ? 1 : 0;
  return anchorB - anchorA;
});

